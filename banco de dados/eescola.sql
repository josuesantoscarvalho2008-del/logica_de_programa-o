DROP DATABASE IF EXISTS escola;
CREATE DATABASE escola;
USE escola;

CREATE TABLE cursos (
    id_curso INT AUTO_INCREMENT PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    carga_horaria INT
);
 

CREATE TABLE modalidades (
    id_modalidade INT AUTO_INCREMENT PRIMARY KEY,
    modalidade VARCHAR(45) NOT NULL,
    id_curso INT,
    FOREIGN KEY (id_curso)
        REFERENCES cursos (id_curso)
);
 

CREATE TABLE disciplinas (
    id_disciplina INT AUTO_INCREMENT PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    carga_horaria INT,
    id_curso INT,
   FOREIGN KEY (id_curso)
        REFERENCES cursos (id_curso)
);
 

CREATE TABLE bibliografias (
    id_bibliografias INT AUTO_INCREMENT PRIMARY KEY,
    bibliografia VARCHAR(255),
    id_disciplina INT,
   FOREIGN KEY (id_disciplina)
        REFERENCES disciplinas (id_disciplina)
);
 

CREATE TABLE turmas (
    id_turma INT AUTO_INCREMENT PRIMARY KEY,
    nome VARCHAR(45) NOT NULL,
    dias_semana VARCHAR(100),
    id_curso INT,
    FOREIGN KEY (id_curso)
        REFERENCES cursos (id_curso)
);
 

CREATE TABLE dias_semana (
    id_dias_semana INT AUTO_INCREMENT PRIMARY KEY,
    dia DATE,
    id_turma INT,
    FOREIGN KEY (id_turma)
        REFERENCES turmas (id_turma)
);
 

CREATE TABLE horarios (
    id_horarios INT AUTO_INCREMENT PRIMARY KEY,
    horario TIME,
    id_turma INT,
    FOREIGN KEY (id_turma)
        REFERENCES turmas (id_turma)
);
 

CREATE TABLE professores (
    id_professor INT AUTO_INCREMENT PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    cpf CHAR(11) NOT NULL
);
 

CREATE TABLE especialidades (
    id_especialidade INT AUTO_INCREMENT PRIMARY KEY,
    especialidade CHAR(11),
    id_professor INT,
    FOREIGN KEY (id_professor)
        REFERENCES professores (id_professor)
);
 

CREATE TABLE telefones_professores (
    id_telefone INT AUTO_INCREMENT PRIMARY KEY,
    telefone CHAR(11) NOT NULL,
    id_professor INT,
    FOREIGN KEY (id_professor)
        REFERENCES professores (id_professor)
);
 

CREATE TABLE turma_professor (
    id_turma_professor INT AUTO_INCREMENT PRIMARY KEY,
    id_turma INT,
    id_professor INT,
    FOREIGN KEY (id_turma)
        REFERENCES turmas (id_turma),
    FOREIGN KEY (id_professor)
        REFERENCES professores (id_professor)
);
 

CREATE TABLE alunos (
    id_aluno INT AUTO_INCREMENT PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    cpf CHAR(11) NOT NULL,
    id_turma INT,
    FOREIGN KEY (id_turma)
        REFERENCES turmas (id_turma)
);
 
 
CREATE TABLE telefones_alunos (
    id_telefone INT AUTO_INCREMENT PRIMARY KEY,
    telefone CHAR(11) NOT NULL,
    id_aluno INT,
    FOREIGN KEY (id_aluno)
        REFERENCES alunos (id_aluno)
);
 

CREATE TABLE emails (
    id_email INT AUTO_INCREMENT PRIMARY KEY,
    email VARCHAR(50) NOT NULL,
    id_aluno INT,
    FOREIGN KEY (id_aluno)
        REFERENCES alunos (id_aluno)
);
 

CREATE TABLE matriculas (
    id_matricula INT AUTO_INCREMENT PRIMARY KEY,
    data_matricula DATE,
    id_aluno INT,
    id_turma INT,
    FOREIGN KEY (id_aluno)
        REFERENCES alunos (id_aluno),
    FOREIGN KEY (id_turma)
        REFERENCES turmas (id_turma)
);
 

CREATE TABLE documentos_entregues (
    id_documentos_entregues INT AUTO_INCREMENT PRIMARY KEY,
    documento_entregue VARCHAR(45),
    id_matricula INT,
    FOREIGN KEY (id_matricula)
        REFERENCES matriculas (id_matricula)
);

